import torch

torch.set_default_dtype(torch.float64)
torch.manual_seed(0)

import experiments_final as ef
from soldiff.dd import Q
from soldiff.device import CoupledSolarCell
from soldiff.tmm import field_intensity

D_TRUE, K_TRUE, TAU_TRUE = 120.0, 0.72, 3.0e-7
V_LIST = ef.V_LIST
LAM_EQE, PHI_EQE, DV = ef.LAM_EQE, ef.PHI_EQE, ef.DV
D_COARSE = [80.0 + 5.0 * i for i in range(45)]      # 80..300 nm, 5 nm step
D0_GRADIENT = 200.0


# ------------------------------------------------- single-pass optical model
def bl_optics(self, d_abs: torch.Tensor, nk_abs: torch.Tensor):
    W, N = self.lam.shape[0], self.dd.N
    d = torch.stack([torch.as_tensor(self.d_etl, dtype=torch.float64),
                     d_abs.reshape(()).to(torch.float64),
                     torch.as_tensor(self.d_htl, dtype=torch.float64)])
    nk = torch.empty(5, W, dtype=torch.complex128)
    nk[0], nk[1] = 1.0, self.nk_etl
    nk[2] = nk_abs.to(torch.complex128)
    nk[3], nk[4] = self.nk_htl, 1.5
    out = field_intensity(nk, d, self.lam)
    a_l = out["a"][2]
    nkj = nk[2]
    alpha = 4.0 * torch.pi * nkj.imag / self.lam
    x_rel = torch.linspace(0.0, 1.0, N, dtype=torch.float64)
    zloc = (x_rel * d[1])[:, None]
    I2 = (a_l * a_l.conj()).real[None, :] * torch.exp(-(alpha[None, :] * zloc))
    nr_over_n0 = nkj.real / nk[0].real
    G_spec = (alpha * self.phi * nr_over_n0)[None, :] * I2
    G = torch.trapz(G_spec, self.lam[None, :].expand_as(G_spec), dim=1) * 1e7
    return G, x_rel, None


def bl_eqe_curve(self, d_abs, nk_abs_eqe, tau, lam_eqe=None, phi_eqe=None,
                 mu=2e-4, ift=False):
    """Identical to CoupledSolarCell.eqe_curve except I2 is single-pass."""
    lam_eqe = self.lam_eqe if lam_eqe is None else lam_eqe
    phi_eqe = self.phi_eqe if phi_eqe is None else phi_eqe
    Weq, N = lam_eqe.shape[0], self.dd.N
    d = torch.stack([torch.as_tensor(self.d_etl, dtype=torch.float64),
                     d_abs.reshape(()).to(torch.float64),
                     torch.as_tensor(self.d_htl, dtype=torch.float64)])
    nk = torch.empty(5, Weq, dtype=torch.complex128)
    nk[0], nk[1] = 1.0, self.nk_etl
    nk[2] = nk_abs_eqe.to(torch.complex128)
    nk[3], nk[4] = self.nk_htl, 1.5
    out = field_intensity(nk, d, lam_eqe)
    a_l = out["a"][2]
    nkj = nk[2]
    lamw = lam_eqe[None, :]
    x_rel = torch.linspace(0.0, 1.0, N, dtype=torch.float64)
    zloc = (x_rel * d[1])[:, None]
    alpha_z = (4.0 * torch.pi * nkj.imag / lamw) * zloc
    I2 = ((a_l * a_l.conj()).real[None, :] * torch.exp(-alpha_z)).clamp(min=0.0)
    alpha = 4.0 * torch.pi * nkj.imag / lam_eqe
    m = self.mesh_diff(d_abs)
    dlam = lam_eqe[1] - lam_eqe[0]
    dark_out = self.dd.solve_state(torch.zeros(self.dd.N), 0.0,
                                   m["dx"], m["psi0"], m["psiL"], tau, tau, mu, mu,
                                   x0=None, ift=ift)
    dark, xw = dark_out["J"], dark_out["x"].detach()
    eqes = []
    for w_i in range(Weq):
        phi_bin = phi_eqe[w_i] * dlam
        nr_over_n0 = nkj.real[w_i] / nk[0].real[w_i]
        G_mesh = (phi_bin * alpha[w_i] * I2[:, w_i] * nr_over_n0) * 1e7 * 1e6
        J = dark
        for s in (1e-2, 0.3, 1.0):
            out2 = self.dd.solve_state(G_mesh * s, 0.0, m["dx"], m["psi0"],
                                       m["psiL"], tau, tau, mu, mu, x0=xw, ift=ift)
            J, xw = out2["J"], out2["x"].detach()
        eqes.append((J - dark) / (Q * phi_bin * 1e4))
    return torch.stack(eqes).clamp(0.0, 1.0)


_ORIG_OPTICS = CoupledSolarCell.optics
_ORIG_EQE = CoupledSolarCell.eqe_curve


class OpticalModel:
    """Context manager swapping the two optical entry points of the cell.

    The originals are captured at import time and restored explicitly; simply
    deleting the patched class attributes would remove the coherent methods
    permanently, since assigning to a class attribute replaces the original.
    """

    def __init__(self, coherent: bool):
        self.coherent = coherent

    def __enter__(self):
        if not self.coherent:
            CoupledSolarCell.optics = bl_optics
            CoupledSolarCell.eqe_curve = bl_eqe_curve
        return self

    def __exit__(self, *exc):
        if not self.coherent:
            CoupledSolarCell.optics = _ORIG_OPTICS
            CoupledSolarCell.eqe_curve = _ORIG_EQE
        return False


def observables(cell, d_abs, grad: bool = False):
    k = torch.tensor(K_TRUE, dtype=torch.float64)
    tau = torch.tensor(TAU_TRUE, dtype=torch.float64)
    with torch.enable_grad() if grad else torch.no_grad():
        J = cell.jv(d_abs, ef.nk_simple(k, cell.lam), tau, V_LIST,
                    ift=grad, dV=DV)
        eqe = cell.eqe_curve(d_abs, ef.nk_simple(k, LAM_EQE), tau,
                             lam_eqe=LAM_EQE, phi_eqe=PHI_EQE, ift=grad)
    return torch.cat([J / 30.0, eqe / 0.9])


def loss_curve(cell, coherent: bool, y_star, grid):
    out, t0 = [], time.time()
    with OpticalModel(coherent):
        for d in grid:
            dd = torch.tensor(float(d), dtype=torch.float64)
            y = observables(cell, dd)
            out.append([float(d), float(((y - y_star) ** 2).mean())])
    return out, time.time() - t0


def thickness_gradient(cell, coherent: bool, y_star, d0):
    with OpticalModel(coherent):
        dd = torch.tensor(d0, dtype=torch.float64, requires_grad=True)
        y = observables(cell, dd, grad=True)
        loss = ((y - y_star) ** 2).mean()
        loss.backward()
        return float(loss.detach()), float(dd.grad.detach())


def main():
    print("E6-OI optical-model misspecification in thickness inversion", flush=True)
    cell = ef.make_cell()
    with OpticalModel(True):
        y_star = observables(cell, torch.tensor(D_TRUE, dtype=torch.float64))
    print(f"  truth d={D_TRUE} nm, k={K_TRUE}, tau={TAU_TRUE:.1e}; "
          f"{y_star.numel()} observations", flush=True)

    arms = {}
    for tag, coherent in (("coherent", True), ("single_pass", False)):
        print(f"  arm {tag}: coarse scan over {len(D_COARSE)} thicknesses", flush=True)
        coarse, tc = loss_curve(cell, coherent, y_star, D_COARSE)
        best = min(coarse, key=lambda r: r[1])
        fine = [best[0] - 4.0 + i for i in range(9)]      # 1 nm refinement
        fine_curve, tf = loss_curve(cell, coherent, y_star, fine)
        joined = sorted(coarse + fine_curve)
        best = min(joined, key=lambda r: r[1])
        l0, g0 = thickness_gradient(cell, coherent, y_star, D0_GRADIENT)
        arms[tag] = {
            "label": "coherent TMM" if coherent else "single-pass Beer--Lambert",
            "best_fit_d_nm": best[0], "best_loss": best[1],
            "loss_at_truth_nm": min(joined, key=lambda r: abs(r[0] - D_TRUE))[1],
            "gradient_at_d0": g0, "loss_at_d0": l0,
            "coarse_curve_d_nm_vs_loss": coarse,
            "fine_curve_d_nm_vs_loss": fine_curve,
            "n_forward_observations": len(joined),
            "wall_clock_s": tc + tf,
        }
        print(f"    best d={best[0]:.2f} nm, loss={best[1]:.4e}, "
              f"dL/dd at {D0_GRADIENT} nm = {g0:.4e}, {tc+tf:.0f}s", flush=True)

    d_coh = arms["coherent"]["best_fit_d_nm"]
    d_bl = arms["single_pass"]["best_fit_d_nm"]
    bias = 100.0 * abs(d_bl - D_TRUE) / D_TRUE
    grad_ratio = arms["single_pass"]["gradient_at_d0"] / arms["coherent"]["gradient_at_d0"]

    readout = {}
    for tag, d in (("coherent", d_coh), ("single_pass", d_bl)):
        dd = torch.tensor(d, dtype=torch.float64)
        with OpticalModel(True):
            y = observables(cell, dd)
            jsc = float(cell.jv(dd,
                                ef.nk_simple(torch.tensor(K_TRUE), cell.lam),
                                torch.tensor(TAU_TRUE), [0.0],
                                ift=False, dV=DV)[0])
        readout[tag] = {
            "observable_rmse_vs_target": float(torch.sqrt(((y - y_star) ** 2).mean())),
            "Jsc_coherent_truth_mA_cm2": jsc,
        }
    truth_jsc = float(y_star[0] * 30.0)

    res = {
        "protocol": {
            "purpose": "direct evidence that coherent optics changes inverse-design outcomes",
            "truth_model": "coherent TMM",
            "truth": {"d_nm": D_TRUE, "k_amp": K_TRUE, "tau_s": TAU_TRUE},
            "observations": "6 J-V points (V_LIST) + 6 EQE points (LAM_EQE), normalised",
            "inverse_variable": "absorber thickness d only; k and tau fixed at truth",
            "why_one_parameter": "the thin stack is weakly identifiable in 3-D with "
                                 "this observable set; both 3-D arms stalled in local "
                                 "minima, which would confound the model-choice test",
            "search": "deterministic dense grid 80..300 nm in 5 nm steps plus a "
                      "1 nm local refinement; no optimiser path dependence",
            "held_fixed": ["electrical solver", "DD mesh N=73", "alpha(lambda)",
                           "AM1.5G flux", "Poynting factor n_r/n_0", "contacts",
                           "k=0.72", "tau=3e-7 s", "grid and budget", "seed 0"],
            "changed": "optical generation model inside the inverse loop ONLY",
            "inverse_crime": True,
            "claim_scope": "model-misspecification bias, NOT experimental identifiability",
        },
        "target": {"J_V_normalised": [float(v) for v in y_star[:len(V_LIST)]],
                   "EQE_normalised": [float(v) for v in y_star[len(V_LIST):]],
                   "Jsc_mA_cm2": truth_jsc},
        "arms": arms,
        "comparison": {
            "thickness_bias_pct": bias,
            "d_shift_nm": d_bl - d_coh,
            "gradient_ratio_BL_over_coherent_at_d0": grad_ratio,
            # Undefined when the correctly specified control attains exactly
            # zero loss.  Do not divide by a floor: that produces a meaningless
            # 1e+296 pseudo-ratio.
            "best_loss_ratio_BL_over_coherent": (None if arms["coherent"]["best_loss"] == 0.0
                else arms["single_pass"]["best_loss"] / arms["coherent"]["best_loss"]),
            "best_loss_ratio_note": "undefined: the correctly specified control attains zero loss",
        },
        "cross_model_consequence": {
            **readout,
            "target_Jsc_mA_cm2": truth_jsc,
            "BL_design_Jsc_deficit_pct":
                100.0 * (readout["coherent"]["Jsc_coherent_truth_mA_cm2"]
                         - readout["single_pass"]["Jsc_coherent_truth_mA_cm2"])
                / abs(readout["coherent"]["Jsc_coherent_truth_mA_cm2"]),
            # Signed, unambiguous restatement of the same two measured currents:
            # positive means the misspecified design yields a HIGHER Jsc under
            # the coherent truth model, i.e. there is no current deficit here.
            "BL_design_Jsc_signed_change_vs_coherent_design_pct":
                100.0 * (readout["single_pass"]["Jsc_coherent_truth_mA_cm2"]
                         - readout["coherent"]["Jsc_coherent_truth_mA_cm2"])
                / abs(readout["coherent"]["Jsc_coherent_truth_mA_cm2"]),
            "BL_design_Jsc_direction": (
                "above the coherent design"
                if readout["single_pass"]["Jsc_coherent_truth_mA_cm2"]
                   > readout["coherent"]["Jsc_coherent_truth_mA_cm2"]
                else "below the coherent design"),
        },
        "interpretation": (
            "The correctly specified control recovers the generating thickness; "
            "the single-pass arm converges to a different, biased thickness "
            "because it compensates for the missing interference term. The "
            "parameter bias, the residual observable mismatch and the altered "
            "loss gradient are model-misspecification effects in a synthetic "
            "inverse crime. Re-evaluated with the coherent truth model, the "
            "misspecified design yields a slightly HIGHER Jsc than the coherent "
            "design at this operating point, so the bias does not translate into "
            "a current penalty here. The result supports retaining coherent "
            "optics for parameter recovery and gradient fidelity in thin, "
            "strongly absorbing stacks; it does not constitute experimental "
            "validation and does not imply that coherent optics is necessary "
            "for Jsc prediction in general."),
    }
    (ROOT / "results_optical_inverse.json").write_text(
        json.dumps(res, indent=1), encoding="utf-8")
    print(json.dumps({"comparison": res["comparison"],
                      "cross_model_consequence": res["cross_model_consequence"]},
                     indent=1), flush=True)


if __name__ == "__main__":
    main()
