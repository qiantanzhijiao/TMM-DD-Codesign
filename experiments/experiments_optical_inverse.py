"""
UniDD -- E6-OI: does the coherent optical model change the inverse design?

Motivation (q/1109 review, q1 Major 1 and q4 "self-ablation undercuts the claim")
-------------------------------------------------------------------------------
The forward ablation only shows that Jsc changes by 0.0071% at the reference
device and that the *thickness gradient* can differ by up to 39.85% in thin,
strongly absorbing stacks.  A reviewer can still ask why coherent optics is
needed for co-design at all.  This experiment answers that directly by holding
the electrical solver, the observations, the initial guess and the search
budget fixed and changing ONLY the optical generation model inside the
inverse loop.

Protocol (pre-specified in this file before execution)
-----------------------------------------------------
* Truth: coherent TMM at d_abs = 120 nm, k_amp = 0.72, tau = 3e-7 s, the
  grid point where the recorded regime scan reports the largest
  thickness-gradient contrast.
* Observations: 6 J--V points and 6 EQE points, all normalised to O(1).
* INVERSE VARIABLE: absorber thickness d only, with k and tau fixed at their
  true values.  A three-parameter version was attempted first, but the thin
  stack is weakly identifiable with this observable set and both arms stalled
  in local minima; that is a known limitation (E4) and would confound the
  model-choice question.  Fixing k and tau isolates the thickness bias the
  reviewers asked about ("Beer--Lambert converges to the wrong thickness").
* Instead of a local optimiser, the loss is evaluated on a DETERMINISTIC
  dense grid over d and refined on a fine local grid.  This removes optimiser
  path dependence completely; the recorded curve is shipped.
* Two arms, same grid and same budget:
  (a) coherent TMM  -- correctly specified control;
  (b) single-pass Beer--Lambert -- misspecified, keeps the same Fresnel
      transmission amplitude, alpha(lambda), AM1.5G flux and n_r/n_0 factor,
      so interference alone is removed.
* Reported: best-fit d and loss for each arm, the thickness bias, the
  thickness-gradient ratio at a common starting thickness, the loss curves,
  and the cross-model consequence (evaluate each recovered design with the
  coherent truth model and compare with the target).
* The target is generated by the same forward model as the control arm, so
  this is a synthetic inverse crime by construction.  What is measured is
  MODEL-MISPECIFICATION BIAS, not experimental identifiability.

Run:  python experiments_optical_inverse.py
Out:  results_optical_inverse.json
"""
from __future__ import annotations

