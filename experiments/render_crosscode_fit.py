"""Render the cross-code fit figure in a SEPARATE process.

Why: on Anaconda/Windows, importing matplotlib in the same process as torch
loads a second copy of ``libiomp5md.dll`` and aborts with
``OMP: Error #15: Initializing libiomp5md.dll, but found libiomp5md.dll
already initialized`` after the numerical fit has already completed.  This
renderer imports no torch, so only one OpenMP runtime is ever initialised.

    python render_crosscode_fit.py <results_crosscode_fit.json> <output_dir>
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt                              # noqa: E402


def main() -> int:
    res = Path(sys.argv[1])
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    r = json.loads(res.read_text(encoding="utf-8"))
    c = r["curves"]

    fig, axes = plt.subplots(1, 3, figsize=(13.5, 3.8))
    ax = axes[0]
    ax.plot(c["scaps_eqe_lambda_nm"], c["scaps_eqe"], color="#c0504d", lw=2,
            label="SCAPS target (external)")
    ax.plot(c["eqe_grid_nm"], c["unidd_truth_eqe"], "o--", color="#1f4e79",
            ms=5, label="UniDD at truth params")
    ax.plot(c["eqe_grid_nm"], c["unidd_fit_eqe"], "s-", color="#2e7d32",
            ms=5, label="UniDD after cross-code fit")
    ax.set_ylim(0, 1.05)
    ax.set_xlabel("wavelength (nm)"); ax.set_ylabel("EQE")
    ax.set_title("EQE: external target vs fit", fontsize=10)
    ax.legend(fontsize=7); ax.grid(alpha=0.3)

    ax = axes[1]
    vals = [r["target"]["jsc_mA_cm2"],
            r["baseline"]["jsc_at_UniDD_truth_mA_cm2"],
            r["fit"]["jsc_after_mA_cm2"]]
    ax.bar(["SCAPS\ntarget", "UniDD\ntruth", "UniDD\nfitted"], vals,
           color=["#c0504d", "#1f4e79", "#2e7d32"], width=0.6)
    ax.set_ylabel("Jsc (mA/cm2)")
    ax.set_title("short-circuit current", fontsize=10)
    for i, v in enumerate(vals):
        ax.text(i, v + 0.4, f"{v:.2f}", ha="center", fontsize=8)
    ax.set_ylim(0, max(vals) * 1.2); ax.grid(alpha=0.3, axis="y")

    ax = axes[2]
    h = r["fit"]["history"]
    ax.semilogy([x[0] for x in h], [max(x[1], 1e-14) for x in h],
                color="#1f4e79", lw=1.6)
    ax.set_xlabel("L-BFGS evaluation"); ax.set_ylabel("weighted residual")
    ax.set_title("fit convergence", fontsize=10); ax.grid(alpha=0.3)

    fig.suptitle("Cross-code surrogate fit -- target generated by SCAPS 3.3.12, "
                 "NOT measured data", fontsize=11, y=1.01)
    fig.tight_layout()
    fig.savefig(out / "crosscode_fit.png", dpi=160, bbox_inches="tight")
    plt.close(fig)
    print(f"figure -> {out / 'crosscode_fit.png'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
